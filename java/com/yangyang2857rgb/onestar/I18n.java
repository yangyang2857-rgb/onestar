    private static boolean isLatAm(String country) {
        if (country == null || country.length() == 0) return false;
        String c = country.toUpperCase(Locale.ROOT);
        if (c.equals("419")) return true;
        String[] list = {
                "MX", "AR", "BO", "CL", "CO", "CR", "CU", "DO", "EC", "GT",
                "HN", "NI", "PA", "PE", "PR", "PY", "SV", "UY", "VE", "US"
        };
        for (int i = 0; i < list.length; i++) {
            if (list[i].equals(c)) return true;
        }
        return false;
    }

    /** 系统语言 -> 语言索引。判定不了的一律英文。 */
    static int detect() {
        Locale l;
        try {
            l = Locale.getDefault();
        } catch (Throwable t) {
            return ZH;
        }
        if (l == null) return ZH;
        String code = l.getLanguage();
        if (code == null || code.length() == 0) return EN;
        code = code.toLowerCase(Locale.ROOT);
        String country = l.getCountry() == null ? "" : l.getCountry();
        String script = l.getScript() == null ? "" : l.getScript().toUpperCase(Locale.ROOT);

        if (code.equals("zh")) {
            if (script.equals("HANT")) return ZH_HANT;
            if (script.equals("HANS")) return ZH;
            String c = country.toUpperCase(Locale.ROOT);
            if (c.equals("TW") || c.equals("HK") || c.equals("MO")) return ZH_HANT;
            return ZH;
        }
        if (code.equals("ja")) return JA;
        if (code.equals("ko")) return KO;
        if (code.equals("fr")) return FR;
        if (code.equals("de")) return DE;
        if (code.equals("es")) return isLatAm(country) ? ES_419 : ES;
        if (code.equals("ar")) return AR;
        if (code.equals("th")) return TH;
        if (code.equals("pt")) {
            return "BR".equalsIgnoreCase(country) ? PT_BR : PT_PT;
        }
        if (code.equals("bo") || code.equals("tib")) return BO;
        if (code.equals("ug")) return UG;
        return EN;
    }

    /** 系统语言可能变，进程却还活着；每次回到前台重新判定一次。 */
    public static void refresh() {
        Integer fl = forcedLang;
        Boolean fe = forcedEn;
        if (fe != null) {
            lang = fe.booleanValue() ? EN : ZH;
        } else if (fl != null) {
            lang = fl.intValue();
        } else {
            lang = detect();
        }
    }

    /** v6.5 兼容：仅测试用，true 锁英文、false 锁中文、null 恢复跟随系统。 */
    public static void force(Boolean english) {
        forcedEn = english;
        if (english != null) forcedLang = null;
        refresh();
    }

