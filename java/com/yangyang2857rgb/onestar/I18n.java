    /**
     * Canvas 手绘文字用：RTL 语言下把逻辑串重排成视觉串（Android 的 drawText 不做 bidi）。
     * 纯 JVM 环境同样可用（java.text.Bidi 是标准库），单测里可以断言结果。
     */
    public static String visual(String s) {
        if (s == null || s.length() == 0 || !rtl()) return s;
        try {
            java.text.Bidi bidi = new java.text.Bidi(s, java.text.Bidi.DIRECTION_DEFAULT_RIGHT_TO_LEFT);
            if (bidi.isLeftToRight()) return s;
            int n = s.length();
            byte[] levels = new byte[n];
            for (int i = 0; i < n; i++) levels[i] = (byte) bidi.getLevelAt(i);
            Character[] chars = new Character[n];
            for (int i = 0; i < n; i++) chars[i] = Character.valueOf(s.charAt(i));
            java.text.Bidi.reorderVisually(levels, 0, chars, 0, n);
            StringBuilder sb = new StringBuilder(n);
            for (int i = 0; i < n; i++) sb.append(chars[i].charValue());
            return sb.toString();
        } catch (Throwable t) {
            return s;
        }
    }

    /** 语言总数与中文原文条数，供单测核对译文表完整性。 */
    public static int rows() {
        return T_ZH.length;
    }

    /** 取某语言某行的译文（单测核对用）。 */
    public static String raw(int language, int index) {
        if (language < 0 || language >= COUNT || index < 0 || index >= rows()) return null;
        return TABLE[language][index];
    }

    /** 某语言的全部行（单测核对用）。 */
    public static String[] column(int language) {
        return language >= 0 && language < COUNT ? TABLE[language] : null;
    }

    /** 中文原文（查表主键）。 */
    public static String zhKey(int index) {
        return index >= 0 && index < rows() ? T_ZH[index] : null;
    }
    /**
     * 系统字体缩放的安全钳制：正文文字最多放大到 1.15 倍、最小 0.90 倍。
     * 星图坐标、海报排版按固定像素绘制，不参与缩放。
     */
    public static float fontScale(float raw) {
        if (Float.isNaN(raw) || raw <= 0f) return 1f;
        if (raw < 0.90f) return 0.90f;
        if (raw > 1.15f) return 1.15f;
        return raw;
    }

