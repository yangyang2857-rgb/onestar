    /** 阿拉伯语是否使用 0-9 西文数字（马格里布地区 nu-latn 习惯），否则用 ٠-٩。 */
    public static boolean arabicLatinDigits() {
        Boolean f = forcedDigits;
        if (f != null) return f.booleanValue();
        if (lang != AR) return true;
        Locale l = Locale.getDefault();
        String nu = null;
        try {
            nu = l == null ? null : l.getUnicodeLocaleType("nu");
        } catch (Throwable t) {
            nu = null;
        }
        if ("latn".equalsIgnoreCase(nu)) return true;
        if ("arab".equalsIgnoreCase(nu)) return false;
        String c = l == null || l.getCountry() == null ? "" : l.getCountry().toUpperCase(Locale.ROOT);
        // 摩洛哥、阿尔及利亚、突尼斯、利比亚通行西文数字
        return c.equals("MA") || c.equals("DZ") || c.equals("TN") || c.equals("LY");
    }

    private static final char[] AR_DIGITS = {
            '\u0660', '\u0661', '\u0662', '\u0663', '\u0664',
            '\u0665', '\u0666', '\u0667', '\u0668', '\u0669'
    };

    /** 把 0-9 换成当前语言习惯的数字字形（目前只有阿拉伯语需要）。 */
    static String digits(String s) {
        if (s == null || s.length() == 0) return s;
        if (lang != AR || arabicLatinDigits()) return s;
        char[] cs = null;
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            if (c >= '0' && c <= '9') {
                if (cs == null) cs = s.toCharArray();
                cs[i] = AR_DIGITS[c - '0'];
            }
        }
        return cs == null ? s : new String(cs);
    }

